def webapp_to_text(data: str):
    try:
        d = json.loads(data)
    except json.JSONDecodeError:
        raise InputError("بيانات المحرر غير صالحة")
    nodes, mem = d.get("nodes", []), d.get("members", [])
    if len(nodes) < 2 or not mem:
        raise InputError("النموذج فاضي")
    N = ";".join(f"{fmt(x, 4)},{fmt(y, 4)}" for x, y in nodes).replace(",", ",")
    N = ";".join(f"{x:g},{y:g}" for x, y in nodes)
    M = ";".join(f"{i + 1}-{j + 1}" for i, j in mem)
    S = ";".join(f"{int(k) + 1}:{v}" for k, v in d.get("supports", {}).items())
    F = ";".join(f"{int(k) + 1}:{v[0]:g},{v[1]:g}" for k, v in d.get("loads", {}).items())
    kind = d.get("kind", "frame")
    t = f"N={N} M={M} S={S}" + (f" F={F}" if F else "")
    if kind == "frame":
        W = ";".join(f"{int(k) + 1}:{v:g}" for k, v in d.get("udl", {}).items())
        if W:
            t += f" W={W}"
    return kind, t


def model3d(res, kind="frame", title=""):
    m = res.model
    if kind == "truss":
        U = [[float(res.disp[2 * i]), float(res.disp[2 * i + 1])] for i in range(len(m.nodes))]
    else:
        U = [[float(res.disp[3 * i]), float(res.disp[3 * i + 1])] for i in range(len(m.nodes))]
    return dict(kind=kind, title=title or f"CivilBot {kind}", nodes=[list(map(float, n)) for n in m.nodes],
                members=[[mm.i, mm.j] for mm in m.members], supports=[[k, v] for k, v in m.supports.items()], disp=U,
                size=[0.3, 0.5] if kind == "frame" else [0.15, 0.15])


def viewer_url(model) -> str | None:
    base = os.getenv("WEBAPP_URL")
    if not base:
        return None
    raw = base64.b64encode(json.dumps(model, separators=(",", ":")).encode()).decode()
    url = base.rstrip("/") + "/viewer3d.html#" + raw
    return url if len(url) < 4000 else None


def viewer_html(model) -> bytes:
    here = os.path.join(os.path.dirname(__file__), "webapp", "viewer3d.html")
    html = open(here, encoding="utf-8").read()
    inject = f"<script>window.__MODEL__={json.dumps(model)};</script>"
    return html.replace("<head>", "<head>" + inject, 1).encode("utf-8")


