def templates_xlsx() -> bytes:
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill
    wb = Workbook()
    wb.remove(wb.active)
    for name, cols in TEMPLATES.items():
        ws = wb.create_sheet(name)
        ws.append(cols)
        for c in ws[1]:
            c.font = Font(bold=True, color="FFFFFF"); c.fill = PatternFill("solid", fgColor="1F6FEB")
        ws.append(EXAMPLES[name])
    buf = io.BytesIO(); wb.save(buf); return buf.getvalue()


def import_xlsx(data: bytes, runners: dict):
    """Each sheet named after a tool; every row is one calculation. Returns (results_xlsx, summary list, special results)."""
    from openpyxl import load_workbook, Workbook
    from openpyxl.styles import Font
    try:
        wb = load_workbook(io.BytesIO(data), data_only=True)
    except Exception:
        raise InputError("ملف Excel غير صالح")
    out = Workbook(); out.remove(out.active)
    summary, specials = [], []
    for ws in wb.worksheets:
        name = ws.title.strip().lower()
        rows = [r for r in ws.iter_rows(values_only=True) if any(v is not None for v in r)]
        if len(rows) < 2:
            continue
        hdr = [str(h).strip() if h is not None else "" for h in rows[0]]
        if name == "schedule" or {"pu", "name"} <= {h.lower() for h in hdr}:
            lines = []
            for r in rows[1:]:
                d = {h.lower(): v for h, v in zip(hdr, r)}
                lines.append(f"{d.get('name')} Pu={d.get('pu')} Mu={d.get('mu') or 0} n={d.get('n') or 1}")
            specials.append(run_schedule("\n".join(lines)))
            summary.append(f"schedule: {len(lines)} columns")
            continue
        if name == "boq":
            lines = []
            for r in rows[1:]:
                d = {h.lower(): v for h, v in zip(hdr, r)}
                dims = "x".join(str(d[k]) for k in ("a", "b", "c") if d.get(k) not in (None, ""))
                lines.append(f"{d.get('element')} {dims} n={d.get('n') or 1}" + (f" kg={d['kg']}" if d.get("kg") else ""))
            specials.append(run_boq("\n".join(lines)))
            summary.append(f"boq: {len(lines)} items")
            continue
        if name not in runners:
            summary.append(f"⚠️ sheet '{ws.title}' ignored (unknown tool)")
            continue
        o = out.create_sheet(name)
        o.append(hdr + ["status", "key results"])
        for c in o[1]:
            c.font = Font(bold=True)
        ok = 0
        for r in rows[1:]:
            text = " ".join(f"{h}={v}" for h, v in zip(hdr, r) if h and v not in (None, ""))
            try:
                res = runners[name](text)
                key = " | ".join(s.result for s in res.steps[-3:] if s.result)
                o.append(list(r) + ["OK" if not res.warnings else "OK (warnings)", key[:500]])
                ok += 1
            except InputError as e:
                o.append(list(r) + ["ERROR", str(e)[:300]])
        summary.append(f"{name}: {ok}/{len(rows) - 1} rows OK")
    buf = io.BytesIO()
    if out.worksheets:
        out.save(buf)
    return (buf.getvalue() if out.worksheets else None), summary, specials
