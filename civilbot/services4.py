def run_layout(img: bytes, caption: str = ""):
    p = _params(caption)
    if "l" not in p:
        raise InputError("أضف في وصف الصورة عرض المبنى الحقيقي بالمتر: layout L=15 span=6")
    return lay.propose(img, _f(p, "l"), _f(p, "span", 6.0), _f(p, "min", 2.5))


def read_equation(img: bytes):
    eq = eqn.read_image(img)
    return eq, eqn.explain(eq)


def eval_equation(eq, text):
    vals = {k: float(v) for k, v in re.findall(r"([A-Za-z_][A-Za-z0-9_]*)\s*=\s*([-+\d.eE]+)", text)}
    if not vals:
        raise InputError("أرسل القيم مثل E=200e6 I=8e-6 L=4")
    return eqn.evaluate(eq, vals)


