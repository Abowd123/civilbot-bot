# ------------------------------------------------------------------ schedule
def _schedule_png(r) -> bytes:
    T = r.outputs["types"]
    n = len(T)
    fig, axs = plt.subplots(1, n, figsize=(2.6 * n + 0.5, 4.6))
    axs = np.atleast_1d(axs)
    for ax, t in zip(axs, T):
        o = t["o"]
        b, h = t["b"], t["h"]
        ax.add_patch(Rectangle((0, 0), b, h, fc="#d0d7de", ec=DARK, lw=2))
        c = o["cover"] + o["tie"] / 2
        ax.add_patch(Rectangle((c, c), b - 2 * c, h - 2 * c, fc="none", ec=GREEN, lw=1.5))
        for x, y in zip(o["xs"], o["ys"]):
            ax.add_patch(Circle((x, h - y), t["db"] / 2, fc=RED, ec="#7a1a1a"))
        ax.set_xlim(-60, max(b, 300) + 60); ax.set_ylim(-420, max(h, 300) + 120); ax.set_aspect("equal"); ax.axis("off")
        ax.text(b / 2, max(h, 300) + 60, t["type"], ha="center", fontsize=13, fontweight="bold", color=BLUE)
        txt = (f"{fmt(b)}×{fmt(h)}\n{t['n']}Ø{t['db']}\nØ{t['tie']}@{t['s']}\nρ={fmt(t['rho']*100, 2)}%\n×{t['count']}: "
               + ",".join(t["members"][:6]) + ("…" if len(t["members"]) > 6 else ""))
        ax.text(b / 2, -40, txt, ha="center", va="top", fontsize=9)
    fig.suptitle("COLUMN SCHEDULE", fontweight="bold")
    return _png(fig)


def _schedule_dxf(r) -> bytes:
    D = dxf.DXF()
    x = 0
    cellw = max(t["b"] for t in r.outputs["types"]) + 400
    hmax = max(t["h"] for t in r.outputs["types"])
    D.text(0, hmax + 700, "COLUMN SCHEDULE - GENERATED BY CivilBot", 80)
    for t in r.outputs["types"]:
        o = t["o"]
        D.rect(x, -900, cellw, hmax + 1500, "DIM")
        x0 = x + (cellw - t["b"]) / 2
        D.rect(x0, 0, t["b"], t["h"])
        c = o["cover"] + o["tie"] / 2
        D.rect(x0 + c, c, t["b"] - 2 * c, t["h"] - 2 * c, "STIRRUP")
        for bx, by in zip(o["xs"], o["ys"]):
            D.dot(x0 + bx, t["h"] - by, t["db"] / 2)
        D.text(x + cellw / 2, hmax + 300, t["type"], 70, align="center")
        for k, line in enumerate([f"{t['b']:.0f}x{t['h']:.0f}", f"{t['n']}T{t['db']}", f"T{t['tie']}@{t['s']}", ",".join(t["members"])[:24]]):
            D.text(x + cellw / 2, -200 - 120 * k, line, 45, align="center")
        x += cellw
    return D.save()


def run_schedule(text):
    first, _, rest = text.partition("\n")
    p = _params(first) if "pu=" not in first.lower() else {}
    body = rest if p else text
    body = re.sub(r"\b(fc|fy|h|cover|rho)\s*=\s*[\d.]+", "", body, flags=re.I) if not p else body
    cols = sch.parse(body)
    r = sch.design_all(cols, _f(p, "fc", 28.0), _f(p, "fy", 420.0), rho_max=_f(p, "rho", 2.5) / 100, cover=_f(p, "cover", 40.0),
                       height=_f(p, "h", 3.2))
    r.images["schedule"] = _schedule_png(r)
    r.files["column_schedule.xlsx"] = sch.to_xlsx(r)
    r.files["column_schedule.dxf"] = _schedule_dxf(r)
    return r


# ------------------------------------------------------------------ BOQ
def _boq_png(r) -> bytes:
    t = r.outputs["totals"]
    keys = [k for k in t if t[k]]
    fig, ax = plt.subplots(figsize=(8, 3.8))
    ax.axis("off")
    rows = [[k, fmt(t[k], 1), r.outputs["unit"][k], fmt(r.outputs["cost"][k], 0) if r.outputs["cost"][k] else "-"] for k in keys]
    tot = sum(r.outputs["cost"].values())
    rows.append(["TOTAL", "", "", fmt(tot, 0) if tot else "-"])
    tb = ax.table(cellText=rows, colLabels=["Item", "Quantity", "Unit", "Cost"], loc="center", cellLoc="center")
    tb.scale(1, 1.6); tb.auto_set_font_size(False); tb.set_fontsize(10)
    for (i, j), c in tb.get_celld().items():
        if i == 0:
            c.set_facecolor(BLUE); c.set_text_props(color="white", fontweight="bold")
        elif i == len(rows):
            c.set_text_props(fontweight="bold")
    ax.set_title("Bill of Quantities — summary", fontweight="bold")
    return _png(fig)


def run_boq(text):
    items, prices = bq.parse(text)
    r = bq.compute(items, prices)
    r.images["boq"] = _boq_png(r)
    r.files["BOQ.xlsx"] = bq.to_xlsx(r)
    return r


